<#
.SYNOPSIS
    Builds and starts the Employee Management System in Docker.

.DESCRIPTION
    Picks free host ports for the app (default 8000) and MySQL (default 3306).
    If a port is taken, the next free one is used - nothing that is already
    running gets stopped. Chosen ports and the APP_KEY are stored in .env.docker
    and reused on the next run.

.EXAMPLE
    .\docker-up.ps1
    .\docker-up.ps1 -AppPort 8080 -DbPort 3310
#>
param(
    [int]$AppPort = 8000,
    [int]$DbPort = 3306,
    [int]$TimeoutMinutes = 20
)

Set-Location -LiteralPath $PSScriptRoot
$envFile = Join-Path $PSScriptRoot '.env.docker'

function Read-EnvFile([string]$Path) {
    $values = @{}
    if (Test-Path -LiteralPath $Path) {
        foreach ($line in Get-Content -LiteralPath $Path) {
            if ($line -match '^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$') {
                $values[$Matches[1]] = $Matches[2]
            }
        }
    }
    return $values
}

function Invoke-Compose([string[]]$Arguments) {
    $base = @('compose')
    if (Test-Path -LiteralPath $envFile) { $base += @('--env-file', $envFile) }
    & docker @($base + $Arguments)
}

# Host ports already published by this project's containers - those may be reused.
function Get-OwnPorts {
    $ports = @()
    foreach ($svc in @(@('app', 80), @('db', 3306))) {
        $out = Invoke-Compose @('port', $svc[0], [string]$svc[1]) 2>$null
        if ($LASTEXITCODE -eq 0 -and $out) {
            foreach ($line in @($out)) {
                if ($line -match ':(\d+)\s*$') { $ports += [int]$Matches[1] }
            }
        }
    }
    return $ports
}

function Test-PortInUse([int]$Port) {
    if (Get-Command Get-NetTCPConnection -ErrorAction SilentlyContinue) {
        if (Get-NetTCPConnection -State Listen -LocalPort $Port -ErrorAction SilentlyContinue) { return $true }
    }
    foreach ($address in @([Net.IPAddress]::Any, [Net.IPAddress]::Loopback)) {
        $listener = New-Object Net.Sockets.TcpListener($address, $Port)
        try {
            $listener.ExclusiveAddressUse = $true
            $listener.Start()
            $listener.Stop()
        } catch {
            return $true
        }
    }
    return $false
}

function Find-FreePort([int]$Start, [int[]]$Exclude, [int[]]$Own) {
    for ($p = $Start; $p -le 65535; $p++) {
        if ($Exclude -contains $p) { continue }
        if ($Own -contains $p) { return $p }
        if (-not (Test-PortInUse $p)) { return $p }
    }
    throw "No free port found starting from $Start"
}

if (-not (Get-Command docker -ErrorAction SilentlyContinue)) {
    Write-Error 'Docker is not installed or not on PATH. Install Docker Desktop: https://www.docker.com/products/docker-desktop/'
    exit 1
}
& docker info *> $null
if ($LASTEXITCODE -ne 0) {
    Write-Error 'Docker is installed but not running. Start Docker Desktop and run this script again.'
    exit 1
}
& docker compose version *> $null
if ($LASTEXITCODE -ne 0) {
    Write-Error 'Docker Compose v2 ("docker compose") is required.'
    exit 1
}

$saved = Read-EnvFile $envFile

$preferredApp = $AppPort
$preferredDb = $DbPort
if (-not $PSBoundParameters.ContainsKey('AppPort') -and $saved.ContainsKey('APP_PORT')) { $preferredApp = [int]$saved['APP_PORT'] }
if (-not $PSBoundParameters.ContainsKey('DbPort') -and $saved.ContainsKey('FORWARD_DB_PORT')) { $preferredDb = [int]$saved['FORWARD_DB_PORT'] }

$own = @(Get-OwnPorts)
$appPortFree = Find-FreePort -Start $preferredApp -Exclude @() -Own $own
$dbPortFree = Find-FreePort -Start $preferredDb -Exclude @($appPortFree) -Own $own

if ($appPortFree -ne $preferredApp) { Write-Host "Port $preferredApp is busy - using $appPortFree for the app." -ForegroundColor Yellow }
if ($dbPortFree -ne $preferredDb) { Write-Host "Port $preferredDb is busy - using $dbPortFree for MySQL." -ForegroundColor Yellow }

$appKey = $saved['APP_KEY']
if (-not $appKey) {
    $bytes = New-Object byte[] 32
    [Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    $appKey = 'base64:' + [Convert]::ToBase64String($bytes)
}

$lines = @(
    '# Generated by docker-up.ps1 / docker-up.sh - used by docker compose --env-file',
    "APP_PORT=$appPortFree",
    "FORWARD_DB_PORT=$dbPortFree",
    "APP_KEY=$appKey"
)
foreach ($key in @('DB_DATABASE', 'DB_USERNAME', 'DB_PASSWORD', 'DB_ROOT_PASSWORD')) {
    if ($saved.ContainsKey($key)) { $lines += "$key=$($saved[$key])" }
}
[IO.File]::WriteAllLines($envFile, $lines, (New-Object Text.UTF8Encoding($false)))

Write-Host 'Building and starting containers...' -ForegroundColor Cyan
Invoke-Compose @('up', '-d', '--build')
if ($LASTEXITCODE -ne 0) {
    Write-Error 'docker compose up failed.'
    exit $LASTEXITCODE
}

$url = "http://localhost:$appPortFree"
Write-Host "Waiting for the app at $url (first start imports the employees dataset, this can take several minutes)..." -ForegroundColor Cyan
$deadline = (Get-Date).AddMinutes($TimeoutMinutes)
$ready = $false
while ((Get-Date) -lt $deadline) {
    try {
        $response = Invoke-WebRequest -Uri $url -UseBasicParsing -TimeoutSec 10
        if ($response.StatusCode -eq 200) { $ready = $true; break }
    } catch { }
    Start-Sleep -Seconds 5
}

if ($ready) {
    Write-Host ''
    Write-Host "App:   $url" -ForegroundColor Green
    Write-Host "MySQL: localhost:$dbPortFree" -ForegroundColor Green
} else {
    Write-Warning "App did not respond within $TimeoutMinutes minutes. Check: docker compose --env-file .env.docker logs -f"
    exit 1
}
