#!/usr/bin/env bash
# Builds and starts the Employee Management System in Docker.
#
# Picks free host ports for the app (default 8000) and MySQL (default 3306).
# If a port is taken, the next free one is used - nothing that is already
# running gets stopped. Chosen ports and the APP_KEY are stored in .env.docker
# and reused on the next run.
#
# Usage: ./docker-up.sh [APP_PORT] [DB_PORT]

set -euo pipefail

cd "$(dirname "$0")"
ENV_FILE=".env.docker"
TIMEOUT_MINUTES="${TIMEOUT_MINUTES:-20}"

saved() { [ -f "$ENV_FILE" ] && grep -E "^$1=" "$ENV_FILE" | tail -n1 | cut -d= -f2- || true; }

compose() {
    if [ -f "$ENV_FILE" ]; then docker compose --env-file "$ENV_FILE" "$@"; else docker compose "$@"; fi
}

port_in_use() {
    local p=$1
    if command -v ss >/dev/null 2>&1; then
        ss -Htln "sport = :$p" 2>/dev/null | grep -q . && return 0
    elif command -v lsof >/dev/null 2>&1; then
        lsof -nP -iTCP:"$p" -sTCP:LISTEN >/dev/null 2>&1 && return 0
    elif command -v netstat >/dev/null 2>&1; then
        netstat -an 2>/dev/null | grep -Eiq "[.:]$p[[:space:]].*LISTEN" && return 0
    fi
    (exec 3<>"/dev/tcp/127.0.0.1/$p") 2>/dev/null && return 0
    return 1
}

# Host ports already published by this project's containers - those may be reused.
OWN_PORTS=" "
for svc in "app 80" "db 3306"; do
    # shellcheck disable=SC2086
    out=$(compose port $svc 2>/dev/null || true)
    [ -n "$out" ] && OWN_PORTS+="${out##*:} "
done

find_free_port() {
    local p=$1 exclude=${2:-}
    while [ "$p" -le 65535 ]; do
        if [ "$p" != "$exclude" ]; then
            [[ "$OWN_PORTS" == *" $p "* ]] && { echo "$p"; return; }
            port_in_use "$p" || { echo "$p"; return; }
        fi
        p=$((p + 1))
    done
    echo "No free port found starting from $1" >&2
    exit 1
}

command -v docker >/dev/null 2>&1 || { echo "Docker is not installed or not on PATH. See https://docs.docker.com/get-docker/" >&2; exit 1; }
docker info >/dev/null 2>&1 || { echo "Docker is installed but not running. Start it and run this script again." >&2; exit 1; }
docker compose version >/dev/null 2>&1 || { echo 'Docker Compose v2 ("docker compose") is required.' >&2; exit 1; }
command -v curl >/dev/null 2>&1 || { echo "curl is required." >&2; exit 1; }

PREFERRED_APP="${1:-$(saved APP_PORT)}"; PREFERRED_APP="${PREFERRED_APP:-8000}"
PREFERRED_DB="${2:-$(saved FORWARD_DB_PORT)}"; PREFERRED_DB="${PREFERRED_DB:-3306}"

APP_PORT=$(find_free_port "$PREFERRED_APP")
DB_PORT=$(find_free_port "$PREFERRED_DB" "$APP_PORT")

[ "$APP_PORT" != "$PREFERRED_APP" ] && echo "Port $PREFERRED_APP is busy - using $APP_PORT for the app."
[ "$DB_PORT" != "$PREFERRED_DB" ] && echo "Port $PREFERRED_DB is busy - using $DB_PORT for MySQL."

APP_KEY="$(saved APP_KEY)"
[ -n "$APP_KEY" ] || APP_KEY="base64:$(head -c 32 /dev/urandom | base64)"

EXTRA=""
for key in DB_DATABASE DB_USERNAME DB_PASSWORD DB_ROOT_PASSWORD; do
    val="$(saved "$key")"
    [ -n "$val" ] && EXTRA+="$key=$val"$'\n'
done

{
    echo "# Generated by docker-up.ps1 / docker-up.sh - used by docker compose --env-file"
    echo "APP_PORT=$APP_PORT"
    echo "FORWARD_DB_PORT=$DB_PORT"
    echo "APP_KEY=$APP_KEY"
    printf '%s' "$EXTRA"
} > "$ENV_FILE"

echo "Building and starting containers..."
compose up -d --build

URL="http://localhost:$APP_PORT"
echo "Waiting for the app at $URL (first start imports the employees dataset, this can take several minutes)..."
deadline=$(( $(date +%s) + TIMEOUT_MINUTES * 60 ))
until [ "$(curl -s -o /dev/null -w '%{http_code}' --max-time 10 "$URL" || true)" = "200" ]; do
    if [ "$(date +%s)" -ge "$deadline" ]; then
        echo "App did not respond within $TIMEOUT_MINUTES minutes. Check: docker compose --env-file $ENV_FILE logs -f" >&2
        exit 1
    fi
    sleep 5
done

echo
echo "App:   $URL"
echo "MySQL: localhost:$DB_PORT"
