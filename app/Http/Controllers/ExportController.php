<?php

namespace App\Http\Controllers;

use App\Enums\ExportFormat;
use App\Services\EmployeeExportService;
use App\Services\QueuedExportService;
use App\Support\EmployeeVisibility;
use App\Support\ExportSelection;
use Illuminate\Http\Request;

class ExportController extends Controller
{
    public function __construct(
        private readonly EmployeeExportService $exports,
        private readonly QueuedExportService $queued,
    ) {}

    /**
     * Bulk export of the directory selection (route behind `can:export-data`).
     * Small exports are downloaded directly; PDFs above EmployeeExportService::PDF_LIMIT
     * rows and CSV / XLSX above the queue threshold are generated by the queue worker
     * and appear under "My exports".
     */
    public function export(Request $request)
    {
        // The manager's department scope and the salary rules are applied to the
        // filters (ids outside the scope are dropped) and to the columns.
        $visibility = EmployeeVisibility::for($request->user());
        $selection = ExportSelection::fromRequest($request);

        if ($selection->isEmpty()) {
            return back()->with('error', __('No employees were selected for export.'));
        }

        $format = ExportFormat::fromInput($request->input('format'));
        $columns = $this->exports->columns($visibility->canSeeSalaries(), $request->input('columns'), $format);
        $query = $selection->query($visibility);

        // Read one id more than a direct download may hold: more means "queue it".
        $directLimit = $format === ExportFormat::Pdf
            ? $this->exports::PDF_LIMIT
            : (int) config('data_tools.exports.queue_threshold', 20000);
        $ids = $query->ids($directLimit + 1);

        if ($ids === []) {
            return back()->with('error', __('No employees found for export.'));
        }

        if (count($ids) > $directLimit) {
            $export = $this->queued->queue($request->user(), $format, $selection, $columns);

            if ($export === null) {
                return back()->with('error', __(
                    'You already have :max exports in progress. Wait until one of them has finished (see My exports).',
                    ['max' => (int) config('data_tools.exports.max_active_per_user', 3)],
                ));
            }

            return redirect()->route('exports.index')->with('status', __(
                'Your :format export is being prepared. It will be listed here when it is ready (export #:id).',
                ['format' => $format->label(), 'id' => $export->id],
            ));
        }

        $this->queued->audit($request->user(), $format, $selection, $columns, count($ids));

        return match ($format) {
            ExportFormat::Pdf => $this->exports->pdf($query, $visibility->canSeeSalaries(), $columns, $ids),
            ExportFormat::Xlsx => $this->exports->xlsx($query, $visibility->canSeeSalaries(), $columns, $ids),
            ExportFormat::Csv => $this->exports->csv($query, $visibility->canSeeSalaries(), $columns, $ids),
        };
    }
}
